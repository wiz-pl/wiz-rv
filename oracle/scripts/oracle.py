def cmd_rvfi(args):
    """Emit a core with the fixture's program, wrap it in rvfi, simulate it with
    Icarus, and compare the rvfi beats with the Python post-states."""
    rep = Report()
    fx = rv32_ref.Fixture(os.path.join(FIXDIR, args.fixture + ".hex"))
    iv = args.iverilog or shutil.which("iverilog")
    if not iv:
        rep.skip("rvfi: iverilog not on PATH "
                 "(nix shell nixpkgs#iverilog -c oracle/scripts/run-oracle.sh rvfi --fixture " + args.fixture + ")")
        return rep.summary()
    vvp = os.path.join(os.path.dirname(iv), "vvp") if os.path.dirname(iv) else shutil.which("vvp")
    if not os.path.exists(vvp):
        vvp = shutil.which("vvp")
    if not vvp:
        rep.skip("rvfi: vvp not on PATH")
        return rep.summary()

    tmp = tempfile.mkdtemp(prefix="rv-oracle-rvfi-")
    core_v = os.path.join(tmp, "core.v")
    rvfi_v = os.path.join(tmp, "rvfi.v")
    sim = os.path.join(tmp, "sim")
    emit = wiz_bin("emit_core", args.emit_bin)
    with open(core_v, "w") as f:
        subprocess.run([emit, os.path.join(FIXDIR, fx.name + ".hex")], check=True, stdout=f)
    subprocess.run([sys.executable, os.path.join(HERE, "mkrvfi.py"),
                    "--verilog", core_v, "--out", rvfi_v], check=True)
    with open(core_v) as f:
        core_text = f.read()
    m = re.search(r"^\s*reg\s+\[[23]:0\]\s+(\w*)ph\s*;", core_text, re.M)
    prefix = m.group(1) if m else ""
    tb_v = os.path.join(tmp, "tb_rvfi.v")
    with open(os.path.join(ROOT, "oracle", "rtl", "tb_rvfi.v.in")) as f:
        tb_text = f.read().replace("${P}", prefix)
    with open(tb_v, "w") as f:
        f.write(tb_text)
    compile_cmd = [iv, "-g2005", "-Wall", "-o", sim, core_v, rvfi_v, tb_v,
                   f"-Ptb_rvfi.STEPS={fx.steps}",
                   f"-Ptb_rvfi.MBASE={fx.mbase}",
                   f"-Ptb_rvfi.MCOUNT={fx.mcount}"]
    print("# " + " ".join(compile_cmd))
    r = subprocess.run(compile_cmd, capture_output=True, text=True)
    if r.returncode != 0:
        rep.fail("rvfi: iverilog compile", (r.stdout + r.stderr).splitlines()[:20])
        return rep.summary()
    r = subprocess.run([vvp, sim], capture_output=True, text=True)
    lines = [l for l in r.stdout.splitlines() if l.startswith("S ")]
    if not lines:
        rep.fail("rvfi: simulation produced no beats", (r.stdout + r.stderr).splitlines()[:20])
        return rep.summary()
    rvfi_tr = parse_trace_text("\n".join(lines), "rvfi:" + fx.name)

    py = parse_trace_text("\n".join(rv32_ref.trace(fx)), "py:" + fx.name)
    # The rvfi beat is a completion, so its state is py's state *after* the
    # instruction: line 1 … line `steps`.
    py_post = Trace(py.states[1:], py.meta)
    ok, detail = compare_traces(py_post, rvfi_tr, f"{fx.name} py-post vs rvfi")
    if ok:
        rep.ok(f"{fx.name} py-post vs rvfi: {len(rvfi_tr.states)} beats")
    else:
        rep.fail(f"{fx.name} py-post vs rvfi", detail)
    return rep.summary()


def cmd_build(args):
    wiz = args.wiz or shutil.which("wiz")
    if not wiz:
        raise SystemExit("wiz not on PATH (use --wiz)")
    os.makedirs(BUILDDIR, exist_ok=True)
    for name, src in (("isa_trace", "isa_trace.wiz"), ("core_trace", "core_trace.wiz"),
                      ("emit_core", "emit_core.wiz")):
        out = os.path.join(BUILDDIR, name)
        cmd = [wiz, "build", os.path.join("oracle", "wiz", src),
               "-I", os.path.join("oracle", "wiz"), "-I", "src", "-o", out]
        print("$ " + " ".join(cmd))
        subprocess.run(cmd, cwd=ROOT, check=True)
    return 0


def fixtures(selected=None):
    names = sorted(f[:-4] for f in os.listdir(FIXDIR) if f.endswith(".hex"))
    if selected:
        want = [s.strip() for s in selected.split(",") if s.strip()]
        unknown = [w for w in want if w not in names]
        if unknown:
            raise SystemExit(f"unknown fixture(s): {', '.join(unknown)} (have: {', '.join(names)})")
        return want
    return names


def cmd_run(args):
    rep = Report()
    tmp = tempfile.mkdtemp(prefix="rv-oracle-")
    os.makedirs(BUILDDIR, exist_ok=True)
    os.makedirs(TRACEDIR, exist_ok=True)
    backends = [b.strip() for b in args.backends.split(",") if b.strip()]
    sail = sail_exe(args.sail)
    spike = spike_exe(args.spike)
    todo = fixtures(args.fixtures)

    for name in todo:
        fx = rv32_ref.Fixture(os.path.join(FIXDIR, name + ".hex"))
        traces = {}
        if "py" in backends:
            traces["py"] = parse_trace_text("\n".join(rv32_ref.trace(fx)), "py:" + name)
        if "isa" in backends:
            traces["isa"] = run_wiz_trace(wiz_bin("isa_trace", args.isa_bin),
                                          os.path.join(FIXDIR, name + ".hex"),
                                          os.path.join(TRACEDIR, f"{name}.isa.trace"))
        if "core" in backends:
            traces["core"] = run_wiz_trace(wiz_bin("core_trace", args.core_bin),
                                           os.path.join(FIXDIR, name + ".hex"),
                                           os.path.join(TRACEDIR, f"{name}.core.trace"))
        trapfixture = name.startswith("trap")
        if "sail" in backends:
            if trapfixture:
                rep.skip(f"{name} sail: the Wiz machine stops on a trap; Sail enters a "
                         f"trap handler (no handler is installed)")
            elif not sail:
                rep.skip(f"{name} sail: sail_riscv_sim not on PATH "
                         f"(nix shell nixpkgs#sail-riscv -c oracle/scripts/run-oracle.sh run --backends sail)")
            else:
                tr, cmd = sail_trace(fx, tmp, sail)
                traces["sail"] = tr
                print(f"# sail: {cmd}")
        if "spike" in backends:
            if trapfixture:
                rep.skip(f"{name} spike: the Wiz machine stops on a trap; Spike enters a "
                         f"trap handler (no handler is installed)")
            elif not spike:
                rep.skip(f"{name} spike: spike not on PATH "
                         f"(nix shell nixpkgs#spike -c oracle/scripts/run-oracle.sh run --backends spike)")
            elif any((w & 0x7F) == 0x17 for w in fx.words):
                # Spike must load the ELF at 0x80000000 (its boot ROM occupies
                # [0, 0x1000)), so AUIPC writes a value relative to that base, while
                # the Wiz side starts at 0.  The difference is the ELF base, not a
                # semantic disagreement; fixtures with AUIPC are Sail/py-only.
                rep.skip(f"{name} spike: fixture contains AUIPC, whose result is "
                         f"relative to Spike's load base 0x80000000")
            else:
                tr, cmd = spike_trace(fx, tmp, spike)
                traces["spike"] = tr
                print(f"# spike: {cmd}")

        # Compare every oracle to `isa` (the specification) and to `core`.
        pairs = []
        if "isa" in traces:
            for other in ("py", "sail", "spike", "core"):
                if other in traces:
                    pairs.append(("isa", other))
        if "core" in traces:
            for other in ("py", "sail", "spike"):
                if other in traces:
                    pairs.append(("core", other))
        if not pairs:
            rep.skip(f"{name}: fewer than two backends available")
            continue
        seen = set()
        for a, b in pairs:
            if (a, b) in seen:
                continue
            seen.add((a, b))
            ok, lines = compare_traces(traces[a], traces[b], f"{name} {a} vs {b}")
            if ok:
                rep.ok(f"{name} {a} vs {b}: {len(traces[a].states)} states")
            else:
                rep.fail(f"{name} {a} vs {b}", lines)
    return rep.summary()


def cmd_diff(args):
    path = args.fixture
    if not os.path.exists(path):
        cand = os.path.join(FIXDIR, path + ".hex")
        if os.path.exists(cand):
            path = cand
    fx = rv32_ref.Fixture(path)
    ref = parse_trace_text("\n".join(rv32_ref.trace(fx)), "py")
    got = parse_trace(args.trace)
    ok, lines = compare_traces(ref, got, f"{fx.name} py vs {args.trace}")
    print("\n".join(lines))
    return 0 if ok else 1


def cmd_versions(args):
    def show(name, path, cmd):
        if not path:
            print(f"{name:12} MISSING")
            return
        try:
            p = subprocess.run([path] + cmd, capture_output=True, text=True, timeout=30)
            out = (p.stdout + p.stderr).strip().splitlines()
            print(f"{name:12} {path}\n             {out[0] if out else '(no version)'}")
        except Exception as e:  # noqa: BLE001
            print(f"{name:12} {path} (version failed: {e})")

    show("sail", sail_exe(args.sail), ["--version"])
    # Spike has no --version; its --help banner carries the version.
    show("spike", spike_exe(args.spike), ["--help"])
    show("wiz", args.wiz or shutil.which("wiz"), ["--version"])
    print(f"{'nixpkgs':12} sail-riscv=0.12 spike=1.1.0-unstable-2026-10-20 "
          f"yosys=0.70 sby=0.70 iverilog=13.0 (the versions this harness was written against)")
    return 0


def cmd_selftest(args):
    """No external tools: isa/core vs py, plus a check that the reporter fails."""
    rep = Report()
    os.makedirs(TRACEDIR, exist_ok=True)
    for name in fixtures(args.fixtures):
        fx = rv32_ref.Fixture(os.path.join(FIXDIR, name + ".hex"))
        py = parse_trace_text("\n".join(rv32_ref.trace(fx)), "py:" + name)
        for backend in ("isa", "core"):
            binpath = args.isa_bin if backend == "isa" else args.core_bin
            try:
                tr = run_wiz_trace(wiz_bin(backend + "_trace", binpath),
                                   os.path.join(FIXDIR, name + ".hex"),
                                   os.path.join(TRACEDIR, f"{name}.{backend}.trace"))
            except SystemExit as e:
                rep.skip(f"{name} {backend}: {e}")
                continue
            ok, lines = compare_traces(py, tr, f"{name} py vs {backend}")
            if ok:
                rep.ok(f"{name} py vs {backend}: {len(py.states)} states")
            else:
                rep.fail(f"{name} py vs {backend}", lines)
        # The reporter must notice a one-bit change: copy the py trace, flip x3, and
        # require a failure.
        bad = Trace([State(s.step, s.pc, s.trap,
                           tuple((r ^ 1) if i == 3 else r for i, r in enumerate(s.regs)), s.mem)
                     for s in py.states], py.meta)
        ok2, _ = compare_traces(py, bad, "selftest")
        if ok2:
            rep.fail("selftest: the comparator missed a perturbed x3")
        else:
            rep.ok("selftest: the comparator catches a perturbed x3")
    return rep.summary()


def main(argv=None):
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--wiz", help="the wiz command (default: wiz on PATH)")
    common.add_argument("--sail", help="sail_riscv_sim (default: PATH)")
    common.add_argument("--spike", help="spike (default: PATH)")
    common.add_argument("--isa-bin", help="the isa_trace binary (default: oracle/.build/isa_trace)")
    common.add_argument("--core-bin", help="the core_trace binary (default: oracle/.build/core_trace)")
    common.add_argument("--emit-bin", help="the emit_core binary (default: oracle/.build/emit_core)")

    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    sp = sub.add_parser("build", parents=[common], help="build the Wiz trace binaries")
    sp.set_defaults(func=cmd_build)

    sp = sub.add_parser("run", parents=[common], help="run the fixture suite")
    sp.add_argument("--fixtures", help="comma-separated fixture names (default: all)")
    sp.add_argument("--backends", default="isa,core,py,sail,spike",
                    help="comma-separated: isa,core,py,sail,spike")
    sp.set_defaults(func=cmd_run)

    sp = sub.add_parser("diff", parents=[common], help="compare a fixture with a trace file")
    sp.add_argument("fixture")
    sp.add_argument("trace")
    sp.set_defaults(func=cmd_diff)

    sp = sub.add_parser("versions", parents=[common], help="print backend versions")
    sp.set_defaults(func=cmd_versions)

    sp = sub.add_parser("selftest", parents=[common],
                        help="isa/core vs py without external tools")
    sp.add_argument("--fixtures", help="comma-separated fixture names (default: all)")
    sp.set_defaults(func=cmd_selftest)

    sp = sub.add_parser("rvfi", parents=[common],
                        help="emit a core, wrap it in rvfi and simulate it (iverilog)")
    sp.add_argument("--fixture", default="alu", help="the fixture (default: alu)")
    sp.add_argument("--iverilog", help="iverilog (default: PATH)")
    sp.set_defaults(func=cmd_rvfi)

    args = p.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
