# A minimal ELF32 writer (no compiler needed)


def build_elf(words, base, text_off=0x1000):
    code = b"".join(struct.pack("<I", w & 0xFFFFFFFF) for w in words)
    shstr = b"\x00.text\x00.shstrtab\x00"
    shstr_off = text_off + len(code)
    shoff = (shstr_off + len(shstr) + 3) & ~3

    def sh(name, typ, flags, addr, off, size, link=0, info=0, align=4, entsize=0):
        return struct.pack("<IIIIIIIIII", name, typ, flags, addr, off, size,
                           link, info, align, entsize)

    sections = (sh(0, 0, 0, 0, 0, 0)
                + sh(1, 1, 6, base, text_off, len(code))
                + sh(7, 3, 0, 0, shstr_off, len(shstr)))
    hdr = bytearray(52)
    hdr[0:4] = b"\x7fELF"
    hdr[4] = 1  # ELFCLASS32
    hdr[5] = 1  # little-endian
    hdr[6] = 1  # EV_CURRENT
    struct.pack_into("<HHIIIIIHHHHHH", hdr, 16,
                     2, 243, 1, base, 52, shoff, 0, 52, 32, 1, 40, 3, 2)
    ph = struct.pack("<IIIIIIII", 1, text_off, base, base, len(code), len(code), 7, 0x1000)
    data = bytearray(bytes(hdr) + ph)
    data += b"\x00" * (text_off - len(data))
    data += code
    data += b"\x00" * (shstr_off - len(data))
    data += shstr
    data += b"\x00" * (shoff - len(data))
    data += sections
    return bytes(data)


