# Trace parsing and comparison


class State:
    __slots__ = ("step", "pc", "trap", "regs", "mem", "tval", "epc", "has_trap")

    def __init__(self, step, pc, trap, regs, mem, tval=None, epc=None):
        self.step = step
        self.pc = pc
        self.trap = trap
        self.regs = regs
        self.mem = mem
        self.tval = tval
        self.epc = epc
        self.has_trap = tval is not None


class Trace:
    def __init__(self, states, meta):
        self.states = states
        self.meta = meta


def parse_trace_text(text, name="<trace>"):
    states = []
    meta = {}
    for lineno, line in enumerate(text.splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        if line.startswith("#"):
            body = line[1:].strip()
            for key in ("fixture", "trace"):
                if body.startswith(key + " "):
                    meta[key] = body[len(key) + 1:]
            if body.startswith("cfg "):
                meta["cfg"] = body[4:]
            continue
        if line.startswith("T "):
            # trap state: T <step> <cause> <tval> <epc>
            f = line.split()
            if len(f) != 5 or not states:
                raise SystemExit(f"{name}:{lineno}: bad trap line: {line[:40]!r}")
            st = states[-1]
            st.trap = int(f[2], 16)
            st.tval = int(f[3], 16)
            st.epc = int(f[4], 16)
            st.has_trap = True
            continue
        if not line.startswith("S "):
            raise SystemExit(f"{name}:{lineno}: not a state line: {line[:40]!r}")
        f = line.split()
        if len(f) < 3 + 32:
            raise SystemExit(f"{name}:{lineno}: state line has {len(f)} fields")
        step = int(f[1])
        pc = int(f[2], 16)
        trap = int(f[3], 16)
        regs = tuple(int(x, 16) for x in f[4:36])
        mem = bytes(int(x, 16) for x in f[36:])
        states.append(State(step, pc, trap, regs, mem))
    return Trace(states, meta)


def parse_trace(path):
    with open(path) as f:
        return parse_trace_text(f.read(), path)


def compare_traces(a, b, label, limit=20, max_steps=10):
    """Compare two Traces.  Return (ok, lines).  `lines` is a report."""
    out = []
    ok = True
    if len(a.states) != len(b.states):
        ok = False
        out.append(f"{label}: state count differs: {len(a.states)} vs {len(b.states)}")
    if a.meta.get("steps") and b.meta.get("steps") and a.meta["steps"] != b.meta["steps"]:
        out.append(f"{label}: warning: steps metadata differs: {a.meta['steps']} vs {b.meta['steps']}")
    bad_steps = 0
    shown = 0
    for i in range(min(len(a.states), len(b.states))):
        sa, sb = a.states[i], b.states[i]
        fields = []
        if sa.pc != sb.pc:
            fields.append(("pc", f"{sa.pc:08x}", f"{sb.pc:08x}"))
        if sa.trap != sb.trap:
            fields.append(("trap", f"{sa.trap}", f"{sb.trap}"))
        if sa.has_trap and sb.has_trap:
            if sa.tval != sb.tval:
                fields.append(("tval", f"{sa.tval:08x}", f"{sb.tval:08x}"))
            if sa.epc != sb.epc:
                fields.append(("epc", f"{sa.epc:08x}", f"{sb.epc:08x}"))
        for r, (x, y) in enumerate(zip(sa.regs, sb.regs)):
            if x != y:
                fields.append((f"x{r}", f"{x:08x}", f"{y:08x}"))
        for j in range(min(len(sa.mem), len(sb.mem))):
            if sa.mem[j] != sb.mem[j]:
                fields.append((f"mem[{j:#06x}]", f"{sa.mem[j]:02x}", f"{sb.mem[j]:02x}"))
        if len(sa.mem) != len(sb.mem):
            fields.append(("mem-length", str(len(sa.mem)), str(len(sb.mem))))
        if not fields:
            continue
        ok = False
        bad_steps += 1
        if bad_steps <= max_steps:
            out.append(f"{label}: step {sa.step} (pc {sa.pc:08x}) differs in {len(fields)} field(s)")
            for fname, va, vb in fields[:limit - shown]:
                out.append(f"    {fname}: {va}  vs  {vb}")
                shown += 1
                if shown >= limit:
                    break
        if bad_steps >= max_steps:
            out.append(f"{label}: … stopping after {max_steps} differing steps")
            break
    if ok:
        out.append(f"{label}: {len(a.states)} states agree")
    return ok, out


