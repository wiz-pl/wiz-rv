def wiz_bin(name, override=None):
    path = override or os.path.join(BUILDDIR, name)
    if not os.path.exists(path):
        raise SystemExit(
            f"{path}: not built; run `python3 oracle/scripts/oracle.py build` "
            f"(or `heavy wiz build oracle/wiz/{name}.wiz -I oracle/wiz -I src -o {path}`)")
    return path


