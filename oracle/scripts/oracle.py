def sail_exe(explicit=None):
    if explicit:
        return explicit
    return shutil.which("sail_riscv_sim")


def spike_exe(explicit=None):
    if explicit:
        return explicit
    return shutil.which("spike")


def sail_trace(fx, tmp, exe):
    elf = os.path.join(tmp, fx.name + ".elf")
    with open(elf, "wb") as f:
        f.write(build_elf(fx.words, 0))
    log = os.path.join(tmp, fx.name + ".sail")
    cfg = SAIL_CFG_M if fx.mx else SAIL_CFG
    cmd = [exe, "--rv32", "--config-override", cfg,
           "--inst-limit", str(fx.steps + 1),
           "--trace-instr", "--trace-gpr", "--trace-mem", "--trace-step",
           "--trace-output", log, elf]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0 or not os.path.exists(log):
        raise RuntimeError(f"sail failed: {' '.join(cmd)}\n{proc.stdout}\n{proc.stderr}")
    return parse_sail_log(log, fx), " ".join(cmd)


def mem_width(insn):
    """Store width in bytes from a store instruction's funct3, else 0."""
    if (insn & 0x7F) != 0x23:
        return 0
    f3 = (insn >> 12) & 7
    return 1 << f3 if f3 <= 2 else 0


def parse_sail_log(path, fx):
    """Sail's `--trace-instr --trace-gpr --trace-mem --trace-step` log.

    Each instruction line is a pre-state (state before the instruction) and the
    register/memory writes that follow it are its effects.  A blank line ends the
    step.  We ask for `steps + 1` instructions and keep the first `steps + 1`
    pre-states, which is exactly the trace L_0 … L_steps.
    """
    states = []
    meta = {"trace": "sail"}
    pc = 0
    regs = [0] * 32
    mem = bytearray(1 << fx.mbits)
    for i, w in enumerate(fx.words):
        mem[4 * i:4 * i + 4] = (w & 0xFFFFFFFF).to_bytes(4, "little")
    pending = []
    with open(path) as f:
        lines = f.read().splitlines()
    for line in lines:
        m = re.match(r"^\[(\d+)\] \[[MSU]\]: 0x([0-9a-fA-F]+) \(0x([0-9a-fA-F]+)\)", line)
        if m:
            for kind, args in pending:
                apply_pending(kind, args, regs, mem, fx)
            pending = []
            pc = int(m.group(2), 16)
            _last_insn[0] = int(m.group(3), 16)
            if len(states) <= fx.steps:
                states.append(make_state(len(states), pc, 0, regs, mem, fx))
            pending = []
            continue
        m = re.match(r"^x(\d+) <- 0x([0-9a-fA-F]+)$", line.strip())
        if m:
            pending.append(("reg", (int(m.group(1)), int(m.group(2), 16))))
            continue
        m = re.match(r"^mem\[W,0x([0-9a-fA-F]+)\] <- 0x([0-9a-fA-F]+)$", line.strip())
        if m:
            pending.append(("mem", (int(m.group(1), 16), int(m.group(2), 16))))
            continue
        if line.strip() == "":
            for kind, args in pending:
                apply_pending(kind, args, regs, mem, fx)
            pending = []
            continue
        if "exception" in line or "trapping" in line:
            raise RuntimeError(f"sail trapped (the fixtures should not): {line}")
    if len(states) <= fx.steps:
        for kind, args in pending:
            apply_pending(kind, args, regs, mem, fx)
    return Trace(states, meta)


def apply_pending(kind, args, regs, mem, fx):
    if kind == "reg":
        r, v = args
        if r != 0:
            regs[r] = v & 0xFFFFFFFF
    else:
        addr, val = args
        # The width comes from the instruction that produced the write.  Sail logs
        # one write per store; the caller has already put the instruction in
        # `_last_insn` (see below).
        width = 4
        if _last_insn[0] is not None:
            width = mem_width(_last_insn[0]) or 4
        for i in range(width):
            mem[(addr + i) & ((1 << fx.mbits) - 1)] = (val >> (8 * i)) & 0xFF


_last_insn = [None]


def make_state(step, pc, trap, regs, mem, fx):
    state_mem = bytes(mem[(fx.mbase + i) % (1 << fx.mbits)] for i in range(fx.mcount))
    return State(step, pc, trap, tuple(regs), state_mem)


def spike_trace(fx, tmp, exe):
    """Spike's log.  The program is loaded at 0x80000000 and data is at 0x2000
    (outside Spike's boot ROM at [0, 0x1000)); program pcs are translated back by
    the load base, which is sound because the fixtures use only PC-relative
    control flow and register-based data addresses."""
    base = 0x80000000
    elf = os.path.join(tmp, fx.name + ".spike.elf")
    with open(elf, "wb") as f:
        f.write(build_elf(fx.words, base))
    log = os.path.join(tmp, fx.name + ".spike.log")
    mem_end = fx.mbase + fx.mcount
    regions = f"0x{fx.mbase:x}:0x{max(0x1000, (mem_end - fx.mbase + 0xfff) & ~0xfff):x},0x80000000:0x10000"
    cmd = [exe, "--isa=" + ("rv32im" if fx.mx else "rv32i"), "--priv=m", "--disable-dtb",
           f"--instructions={fx.steps + 1}",
           "-m" + regions, "-l", "--log-commits", elf]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    text = proc.stdout + proc.stderr
    return parse_spike_log(text, fx, base), " ".join(cmd)


def parse_spike_log(text, fx, base):
    """Spike `--log-commits`: each `core 0: 3 0x<pc> (0x<insn>) …` line is the
    commit of one instruction; the state before it is the trace's pre-state (with
    the pc translated by the ELF's load base)."""
    states = []
    meta = {"trace": "spike"}
    regs = [0] * 32
    mem = bytearray(1 << fx.mbits)
    for i, w in enumerate(fx.words):
        mem[4 * i:4 * i + 4] = (w & 0xFFFFFFFF).to_bytes(4, "little")
    commit = re.compile(r"^core\s+\d+:\s+\d+\s+0x([0-9a-fA-F]+) \(0x([0-9a-fA-F]+)\)(.*)$")
    for line in text.splitlines():
        m = commit.match(line)
        if not m:
            continue
        ipc = int(m.group(1), 16)
        insn = int(m.group(2), 16)
        tail = m.group(3)
        if len(states) > fx.steps:
            break
        states.append(make_state(len(states), max(0, ipc - base), 0, regs, mem, fx))
        for r, v in re.findall(r"\bx(\d+)\s+0x([0-9a-fA-F]+)", tail):
            if int(r) != 0:
                regs[int(r)] = int(v, 16) & 0xFFFFFFFF
        for addr, val in re.findall(r"\bmem\s+0x([0-9a-fA-F]+)(?:\s+0x([0-9a-fA-F]+))?", tail):
            if not val:
                continue
            width = mem_width(insn) or 4
            a = int(addr, 16)
            v = int(val, 16)
            for i in range(width):
                if a + i < (1 << fx.mbits):
                    mem[(a + i) % (1 << fx.mbits)] = (v >> (8 * i)) & 0xFF
    return Trace(states, meta)


# ---------------------------------------------------------------------------
# Reporting


class Report:
    def __init__(self):
        self.passed = 0
        self.failed = 0
        self.skipped = 0

    def ok(self, msg):
        self.passed += 1
        print(f"PASS {msg}")

    def fail(self, msg, detail=()):
        self.failed += 1
        print(f"FAIL {msg}")
        for line in detail:
            print("  " + line)

    def skip(self, msg):
        self.skipped += 1
        print(f"SKIP {msg}")

    def summary(self):
        print(f"\n{self.passed} passed, {self.failed} failed, {self.skipped} skipped")
        return 0 if self.failed == 0 else 1


