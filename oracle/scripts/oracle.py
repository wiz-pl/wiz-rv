#!/usr/bin/env python3
"""The independent-oracle harness for wiz-rv.

It compares four implementations of the same RV32I/RV32IM machine on one
instruction trace at a time:

    isa    Rv.Isa        the Wiz executable specification (src/Rv/Isa.wiz)
    core   Rv.Core       the multi-cycle core, projected at its E phase
    py     oracle/scripts/rv32_ref.py   an independent reference interpreter
    sail   sail-riscv    the Sail RISC-V model (external)
    spike  Spike         the RISC-V ISS (external)

`isa` and `core` are generated by Wiz programs in oracle/wiz/; `py` is always
available; `sail` and `spike` are used when they are on PATH (or given with
--sail/--spike) and skipped with a message otherwise.

Commands
    build                 build the two Wiz trace binaries (needs `wiz`)
    run [OPTIONS]         run the fixture suite and compare
    diff A TRACE          compare a fixture with one trace file
    versions              print the versions of every backend
    selftest              isa/core vs py, and a check that the reporter fails a
                          deliberately perturbed trace (needs no external tools)

Examples
    python3 oracle/scripts/oracle.py build
    python3 oracle/scripts/oracle.py run
    nix shell nixpkgs#sail-riscv nixpkgs#spike -c \\
        python3 oracle/scripts/oracle.py run
    python3 oracle/scripts/oracle.py run --fixtures alu,branch --backends py,sail

The trace format is documented in oracle/wiz/OracleTrace.wiz.  A skipped backend
is not a pass: the summary prints `pass`, `FAIL` and `SKIP` counts separately and
exits 0 only when no comparison failed.
"""
